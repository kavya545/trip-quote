// Writes src/tokens.css (CSS custom properties) and design-tokens.json from src/tokens.ts.
// design-tokens.json uses the W3C design-token format; each token names the Figma variable it is bound to.
// Run with: npm run tokens
import { writeFileSync } from 'node:fs';
import { cssVar, tokens, type ColorToken } from '../src/tokens.ts';

const names = Object.keys(tokens) as ColorToken[];
const css = `/* Generated by \`npm run tokens\` from src/tokens.ts. Do not edit by hand. */\n:root{\n${names.map(n => `  ${cssVar(n)}:${tokens[n].value};`).join('\n')}\n}\n`;
writeFileSync(new URL('../src/tokens.css', import.meta.url), css);

const json = {
  $description: 'Trip Quote colour tokens, generated from src/tokens.ts. Each token is bound to a variable in the AI-Native Workflow Figma file.',
  color: Object.fromEntries(names.map(n => [n, {
    $type: 'color', $value: tokens[n].value, $description: tokens[n].use,
    $extensions: { 'com.figma': { file: 'FFULIvAdvUc29HzIiLXXla', collection: tokens[n].figma.collection, variable: tokens[n].figma.name, variableId: tokens[n].figma.id } },
  }])),
};
writeFileSync(new URL('../design-tokens.json', import.meta.url), JSON.stringify(json, null, 2) + '\n');
console.log(`src/tokens.css and design-tokens.json: ${names.length} tokens`);
